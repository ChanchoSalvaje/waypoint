-- A transaction-consistent, service-only export including private CSV provenance.
grant usage on schema waypoint_migration to service_role;
grant select on all tables in schema waypoint_migration to service_role;
create or replace function public.waypoint_backup_snapshot()
returns jsonb language plpgsql security invoker set search_path=''
as $$
declare rel record; rows jsonb; result jsonb='{}'; definitions jsonb='[]'; column_sql text;
begin
 for rel in
  select c.oid,n.nspname,c.relname,c.relrowsecurity,c.relforcerowsecurity,c.relacl,
   pg_catalog.obj_description(c.oid,'pg_class') as description
  from pg_catalog.pg_class c join pg_catalog.pg_namespace n on n.oid=c.relnamespace
  where c.relkind='r' and (n.nspname='waypoint_migration' or
   (n.nspname='public' and c.relname like 'waypoint\_%' escape '\'))
  order by n.nspname,c.relname
 loop
  execute format('select coalesce(jsonb_agg(to_jsonb(t) order by to_jsonb(t)::text),''[]'') from %I.%I t',rel.nspname,rel.relname) into rows;
  result=result||jsonb_build_object(rel.nspname||'.'||rel.relname,rows);
  select string_agg(format('%I %s%s%s%s',a.attname,
   pg_catalog.format_type(a.atttypid,a.atttypmod),
   case when a.attidentity='a' then ' generated always as identity' when a.attidentity='d' then ' generated by default as identity' else '' end,
   case when a.attidentity='' and d.adbin is not null then ' default '||pg_catalog.pg_get_expr(d.adbin,d.adrelid) else '' end,
   case when a.attnotnull then ' not null' else '' end),',' order by a.attnum)
  into column_sql from pg_catalog.pg_attribute a left join pg_catalog.pg_attrdef d on d.adrelid=a.attrelid and d.adnum=a.attnum
  where a.attrelid=rel.oid and a.attnum>0 and not a.attisdropped;
  definitions=definitions||jsonb_build_array(jsonb_build_object(
   'name',rel.nspname||'.'||rel.relname,
   'create',format('create table %I.%I (%s);',rel.nspname,rel.relname,column_sql),
   'rls',rel.relrowsecurity,'forceRls',rel.relforcerowsecurity,'acl',rel.relacl,'comment',rel.description,
   'constraints',(select coalesce(jsonb_agg(jsonb_build_object('name',con.conname,'definition',pg_catalog.pg_get_constraintdef(con.oid))), '[]') from pg_catalog.pg_constraint con where con.conrelid=rel.oid),
   'indexes',(select coalesce(jsonb_agg(pg_catalog.pg_get_indexdef(i.indexrelid)),'[]') from pg_catalog.pg_index i where i.indrelid=rel.oid and not exists(select 1 from pg_catalog.pg_constraint con where con.conindid=i.indexrelid)),
   'triggers',(select coalesce(jsonb_agg(pg_catalog.pg_get_triggerdef(t.oid)),'[]') from pg_catalog.pg_trigger t where t.tgrelid=rel.oid and not t.tgisinternal),
   'policies',(select coalesce(jsonb_agg(to_jsonb(p)),'[]') from pg_catalog.pg_policies p where p.schemaname=rel.nspname and p.tablename=rel.relname)
  ));
 end loop;
 return jsonb_build_object('version',1,'capturedAt',transaction_timestamp(),'databaseBytes',pg_catalog.pg_database_size(current_database()),
 'data',result,'schema',definitions,
 'functions',(select coalesce(jsonb_agg(jsonb_build_object('definition',pg_catalog.pg_get_functiondef(p.oid),'acl',p.proacl,'identity',p.oid::regprocedure::text)),'[]')
  from pg_catalog.pg_proc p join pg_catalog.pg_namespace n on n.oid=p.pronamespace where n.nspname='public' and p.proname like 'waypoint\_%' escape '\'),
 'rolesWithoutPasswords',(select jsonb_agg(jsonb_build_object('name',rolname,'inherit',rolinherit,'login',rolcanlogin,'bypassRls',rolbypassrls)) from pg_catalog.pg_roles where rolname in ('anon','authenticated','service_role')),
 'storageFileCoverage','No source attachment values or stored files at cutover; historical record comments remain in Airtable by owner instruction.');
end;
$$;
revoke all on function public.waypoint_backup_snapshot() from public,anon,authenticated;
grant execute on function public.waypoint_backup_snapshot() to service_role;
